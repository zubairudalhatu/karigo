const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { partnerApiTarget, runtimePartnerApiTarget } = require('../config/api-target.cjs');
const root = path.resolve(__dirname, '..');
const prod = 'https://karigo-8htn.onrender.com/api/v1';
assert.throws(() => partnerApiTarget(true, { EXPO_PUBLIC_API_BASE_URL: prod }));
assert.throws(() => partnerApiTarget(true, { PARTNER_STAGING_API_BASE_URL: prod }));
assert.throws(() => partnerApiTarget(true, { PARTNER_STAGING_API_BASE_URL: 'http://stage.invalid/api/v1' }));
assert.throws(() => partnerApiTarget(true, { PARTNER_STAGING_API_BASE_URL: 'https://user:secret@stage.invalid/api/v1' }));
assert.equal(partnerApiTarget(true, { PARTNER_STAGING_API_BASE_URL: 'https://stage.invalid/api/v1' }), 'https://stage.invalid/api/v1');
assert.equal(partnerApiTarget(false, { EXPO_PUBLIC_API_BASE_URL: prod }), prod);
assert.throws(() => runtimePartnerApiTarget(undefined));
assert.throws(() => runtimePartnerApiTarget({ apiBaseUrl: '' }));
assert.throws(() => runtimePartnerApiTarget({ appVariant: 'staging', apiBaseUrl: prod }));
assert.equal(runtimePartnerApiTarget({ appVariant: 'staging', apiBaseUrl: 'https://stage.invalid/api/v1' }), 'https://stage.invalid/api/v1');
const eas = JSON.parse(fs.readFileSync(path.join(root, 'eas.json')));
for (const profile of ['partner-staging', 'partner-staging-ios-simulator']) assert.equal(eas.build[profile].env.EXPO_PUBLIC_API_BASE_URL, undefined);
assert.equal(eas.build['partner-production'].env.EXPO_PUBLIC_API_BASE_URL, prod);
const config = fs.readFileSync(path.join(root, 'app.config.ts'), 'utf8');
for (const permission of ['cameraPermission', 'microphonePermission', 'photosPermission']) assert(config.includes(`${permission}: false`));
assert(config.includes('supportsTablet: false'));
assert(config.includes('"ng.com.karigo.partner.staging" : "ng.com.karigo.partner"'));
assert(config.includes('"com.karigo.partner.staging" : "com.karigo.partner"'));
const client = fs.readFileSync(path.join(root, 'src/api/client.ts'), 'utf8');
assert(client.includes('keychainAccessible: SecureStore.WHEN_UNLOCKED'));
assert(!client.includes('AFTER_FIRST_UNLOCK'));
const picker = fs.readFileSync(path.join(root, 'src/lib/upload-pickers.ts'), 'utf8');
assert(!picker.includes('requestMediaLibraryPermissionsAsync'));
assert(!picker.includes('launchCameraAsync'));
assert(picker.includes('allowsEditing: false'));
console.log('Partner P1 staging, permissions, identity and storage guards passed.');
